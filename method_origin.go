package rasql

import (
	"fmt"
	"reflect"
	"runtime"
	"strings"
)

// generatedMethodFile is the file name the Go toolchain reports for a method it
// generates rather than one a package declares, such as the wrapper that
// promotes an embedded field's method to the outer struct.
//
// This name is the only signal that separates a promoted method from a declared
// one. The two are indistinguishable everywhere else reflect can look: they
// occupy the same slot of the same method set, the wrapper is named after the
// outer type just as a declared method is, and its code pointer is its own
// rather than the embedded method's. It is a property of the toolchain rather
// than of the language, so TestGeneratedMethodsReportGeneratedFile states it for
// every shape the mapping rules rest on, and methodOriginOf refuses to guess
// when a build reports something else.
const generatedMethodFile = "<autogenerated>"

// methodOrigin says where the implementation behind a method came from.
type methodOrigin int

const (
	// methodOriginNone means the type has no such method at all.
	methodOriginNone methodOrigin = iota
	// methodOriginDeclared means a package declares the method in a source file.
	methodOriginDeclared
	// methodOriginGenerated means the toolchain generated the method: either the
	// wrapper that promotes an embedded field's method, or the pointer type's
	// copy of a value-receiver method.
	methodOriginGenerated
	// methodOriginUnknown means the toolchain reported neither, so this build
	// cannot tell a declared method from a generated one.
	methodOriginUnknown
)

// declaresMethod reports whether rowType declares the named method itself rather
// than promoting it from an embedded field. Both rowType and its pointer are
// asked, because a value receiver is declared on the value type and a pointer
// receiver on the pointer type, and the pointer type's copy of a value-receiver
// method is generated just as a promoted one is, so only the pair of answers
// separates the two cases. A build that reports an origin for neither is an
// error rather than a guess: guessing routes a row type by the wrong mapping and
// binds the wrong values silently, and an error says so.
func declaresMethod(rowType reflect.Type, name string) (bool, error) {
	for _, methodType := range []reflect.Type{rowType, reflect.PointerTo(rowType)} {
		origin, file := methodOriginOf(methodType, name)
		if origin == methodOriginDeclared {
			return true, nil
		}
		if origin == methodOriginUnknown {
			return false, fmt.Errorf("cannot tell whether %s declares %s or promotes it from an embedded field: this Go build reports %q as the file of the method, and rasql reads only a source file name (declared) or %q (generated)", methodType, name, file, generatedMethodFile)
		}
	}
	return false, nil
}

// methodOriginOf reports where the named method of methodType came from, along
// with the file name the answer was read from.
func methodOriginOf(methodType reflect.Type, name string) (methodOrigin, string) {
	method, ok := methodType.MethodByName(name)
	if !ok {
		return methodOriginNone, ""
	}
	function := runtime.FuncForPC(method.Func.Pointer())
	if function == nil {
		return methodOriginUnknown, ""
	}
	file, _ := function.FileLine(method.Func.Pointer())
	return originForFile(file), file
}

// originForFile classifies the file name a build reports for a method. A
// generated method is reported as generatedMethodFile and a declared one as the
// path of the file holding it. Anything else -- no name at all, the "?" the
// runtime reports when it has no line table, or another placeholder written in
// angle brackets -- is a name this build was not written against.
func originForFile(file string) methodOrigin {
	if file == generatedMethodFile {
		return methodOriginGenerated
	}
	if file == "" || file == "?" || strings.HasPrefix(file, "<") {
		return methodOriginUnknown
	}
	return methodOriginDeclared
}
