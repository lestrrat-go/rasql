package schemagen_test

import (
	"testing"

	"github.com/lestrrat-go/rasql/internal/schemagen"
	"github.com/stretchr/testify/require"
)

// TestHintsSourceRejectsInvalidPackageName pins the same guard
// DescriptionSource and TablesFuncSource apply to packageName.
func TestHintsSourceRejectsInvalidPackageName(t *testing.T) {
	_, err := schemagen.HintsSource("not a package name")
	require.ErrorContains(t, err, "invalid package name")
}

// TestHintsSourceWritesEmptyEditableMap pins the shape a bootstrap-written
// hints.go carries the very first time it exists: an empty map ready for a
// caller to fill in by hand, under a header that names rasqlgen as the
// writer but deliberately does not say "DO NOT EDIT." -- unlike every other
// file rasqlgen writes into a description package, this one is meant to be
// edited.
func TestHintsSourceWritesEmptyEditableMap(t *testing.T) {
	source, err := schemagen.HintsSource("tables")
	require.NoError(t, err)

	text := string(source)
	require.Contains(t, text, "// Code generated by rasqlgen once; edit freely.")
	require.NotContains(t, text, "DO NOT EDIT")
	require.Contains(t, text, "package tables")
	require.Contains(t, text, `import "github.com/lestrrat-go/rasql/schema"`)
	require.Contains(t, text, "var Hints = map[string]schema.TableHint{}")
}

// TestTablesFuncSourceAppliesHints pins that the aggregator Tables function
// applies every entry in Hints, by table name, before returning -- the
// mechanism that makes a hint set once in hints.go survive every later
// refresh, since this file is rewritten on every refresh but always emits
// the same application loop.
func TestTablesFuncSourceAppliesHints(t *testing.T) {
	source, err := schemagen.TablesFuncSource("tables", []string{"OrdersDef", "UsersDef"})
	require.NoError(t, err)

	text := string(source)
	require.Contains(t, text, "func Tables() []schema.TableDef {")
	require.Contains(t, text, "OrdersDef(),")
	require.Contains(t, text, "UsersDef(),")
	require.Contains(t, text, "if hint, ok := Hints[table.Name]; ok {")
	require.Contains(t, text, "tables[index] = hint.Apply(table)")
}

// TestTablesFuncSourceRejectsInvalidPackageName is unchanged by hints and
// pinned again here so a future edit to the shared validation cannot drop
// it unnoticed.
func TestTablesFuncSourceRejectsInvalidPackageName(t *testing.T) {
	_, err := schemagen.TablesFuncSource("not a package name", []string{"UsersDef"})
	require.ErrorContains(t, err, "invalid package name")
}
