package schemagen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"unicode"
	"unicode/utf8"

	"github.com/lestrrat-go/rasql/schema"
)

// DescriptionFuncName returns the exported function name a bootstrap-written
// description file uses for tableName. It reuses definitionAccessorName's
// own derivation, the name a generated store package already gives the
// accessor that hands back a table's schema.TableDef, since both name "the
// descriptor for this table."
func DescriptionFuncName(tableName string) string {
	return definitionAccessorName(tableName)
}

// DescriptionSource returns a single-table file for a bootstrap-written
// description package: an exported function named funcName that returns
// table's schema.TableDef literal.
//
// Unlike DescriptorSource, this never merges a derived relationship into
// the literal it writes: table is rendered exactly as given, because the
// description package is meant to round-trip through `rasqlgen schema
// -source` unchanged, and deriving a relationship from a foreign key is
// that command's job, not this one's.
func DescriptionSource(packageName, funcName string, table schema.TableDef) ([]byte, error) {
	if !token.IsIdentifier(packageName) {
		return nil, fmt.Errorf("generate: invalid package name %q", packageName)
	}
	if !isExportedIdentifier(funcName) {
		return nil, fmt.Errorf("generate: invalid function name %q", funcName)
	}
	if err := table.Validate(); err != nil {
		return nil, fmt.Errorf("generate: table %q: %w", table.Name, err)
	}

	var source bytes.Buffer
	source.WriteString("// Code generated by rasqlgen; DO NOT EDIT.\n\n")
	source.WriteString("package ")
	source.WriteString(packageName)
	source.WriteString("\n\n")
	source.WriteString("import \"github.com/lestrrat-go/rasql/schema\"\n\n")
	source.WriteString("// ")
	source.WriteString(funcName)
	source.WriteString(" returns the schema.TableDef bootstrap inspected for the ")
	source.WriteString(quote(table.Name))
	source.WriteString(" table.\n")
	source.WriteString("func ")
	source.WriteString(funcName)
	source.WriteString("() schema.TableDef {\n\treturn ")
	writeTableDefLiteral(&source, table)
	source.WriteString("\n}\n")

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generate: format source: %w", err)
	}
	return formatted, nil
}

// TablesFuncSource returns the aggregator file a bootstrap-written
// description package writes once: the exported func Tables()
// []schema.TableDef that `rasqlgen schema -source` reads, calling every
// name in funcNames in the order given.
func TablesFuncSource(packageName string, funcNames []string) ([]byte, error) {
	if !token.IsIdentifier(packageName) {
		return nil, fmt.Errorf("generate: invalid package name %q", packageName)
	}

	var source bytes.Buffer
	source.WriteString("// Code generated by rasqlgen; DO NOT EDIT.\n\n")
	source.WriteString("package ")
	source.WriteString(packageName)
	source.WriteString("\n\n")
	source.WriteString("import \"github.com/lestrrat-go/rasql/schema\"\n\n")
	source.WriteString("// Tables returns every table this package describes, in the order\n")
	source.WriteString("// bootstrap wrote them.\n")
	source.WriteString("func Tables() []schema.TableDef {\n\treturn []schema.TableDef{\n")
	for _, name := range funcNames {
		source.WriteString("\t\t")
		source.WriteString(name)
		source.WriteString("(),\n")
	}
	source.WriteString("\t}\n}\n")

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generate: format source: %w", err)
	}
	return formatted, nil
}

// isExportedIdentifier reports whether name is a valid, exported Go
// identifier. token.IsIdentifier accepts an unexported one too, so the
// first rune is checked separately.
func isExportedIdentifier(name string) bool {
	if !token.IsIdentifier(name) {
		return false
	}
	first, _ := utf8.DecodeRuneInString(name)
	return unicode.IsUpper(first)
}
