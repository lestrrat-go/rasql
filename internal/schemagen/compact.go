// CompactObject is the canonical input for one compact generated object file.
// The renderer consumes all four compiler layers so generated declarations do
// not have to rediscover physical facts from the Go model.
type CompactObject struct {
	Catalog        compilerir.PhysicalObject
	Semantic       compilerir.SemanticObject
	Go             compilerir.GoObject
	Generation     compilerir.ObjectGoName
	Table          schema.TableDef
	Mappings       []compilerir.ScalarMapping
	ColumnBindings []compilerir.ColumnGoBinding
	Targets        map[compilerir.ObjectID]CompactObjectRef
}

// CompactObjectRef carries the canonical names and relation facts needed by
// declarations that connect one generated object to another.
type CompactObjectRef struct {
	Catalog        compilerir.PhysicalObject
	Semantic       compilerir.SemanticObject
	Go             compilerir.GoObject
	Generation     compilerir.ObjectGoName
	Table          schema.TableDef
	ColumnBindings []compilerir.ColumnGoBinding
}

// CompactObjectSource emits the compact table or view declarations for one
// object. It returns one formatted source file and never performs database
// work or retains mutable input state.
//
// It also returns one warning per column it left out because the Go name that
// column wants is already spent. Leaving one out never stops generation: the
// table is still created with the column, and Table.Ref().Column(name) still
// reaches it under its database name.
func CompactObjectSource(packageName string, object CompactObject) ([]byte, []compilerir.Diagnostic, error) {
	if packageName == "" || object.Generation.File == "" {
		return nil, nil, fmt.Errorf("compact: package and output file are required")
	}
	definition, err := TableDefinitionLiteral(object.Table)
	if err != nil {
		return nil, nil, err
	}
	row := object.Generation.Row
	if row == "" {
		row = exportedCompact(object.Catalog.Name) + "Row"
	}
	accessor := object.Generation.Source
	if accessor == "" {
		accessor = exportedCompact(object.Catalog.Name)
	}
	if row == "" || accessor == "" {
		return nil, nil, fmt.Errorf("compact: object %q has incomplete generated names", object.Catalog.ID)
	}
	omissions, warnings := resolveCompactColumns(object, accessor)
	hasMutations := object.Table.Supports(schema.OperationInsert) ||
		object.Table.Supports(schema.OperationUpdate) ||
		object.Table.Supports(schema.OperationDelete)
	var b bytes.Buffer
	b.WriteString("// Code generated by rasqlgen; DO NOT EDIT.\n\npackage ")
	b.WriteString(packageName)
	b.WriteString("\n\nimport (\n")
	if hasMutations {
		b.WriteString("\t\"context\"\n")
	}
	b.WriteString("\t\"github.com/lestrrat-go/rasql\"\n")
	b.WriteString("\t\"github.com/lestrrat-go/rasql/query\"\n")
	b.WriteString("\t\"github.com/lestrrat-go/rasql/schema\"\n")
	for _, imp := range compactImports(object) {
		b.WriteString("\t")
		if imp.Alias != "" {
			b.WriteString(imp.Alias)
			b.WriteByte(' ')
		}
		b.WriteString(strconv.Quote(imp.Path))
		b.WriteByte('\n')
	}
	b.WriteString(")\n\n")
	b.WriteString("type ")
	b.WriteString(row)
	b.WriteString(" struct {\n")
	for _, group := range compactFieldGroups(omissions, object.Go.Row.Fields) {
		b.WriteString("\t")
		b.WriteString(strings.Join(group.Names, ", "))
		b.WriteByte(' ')
		b.WriteString(group.Type)
		b.WriteByte('\n')
	}
	b.WriteString("}\n\n")

	definitionName := compactLowerFirst(accessor) + "Definition"
	tableName := compactLowerFirst(accessor) + "Table"
	b.WriteString("var ")
	b.WriteString(definitionName)
	b.WriteString(" = ")
	b.WriteString(definition)
	b.WriteString("\n\n")
	b.WriteString("var ")
	b.WriteString(tableName)
	b.WriteString(" = rasql.MustTableOf[")
	b.WriteString(row)
	b.WriteString("](")
	b.WriteString(definitionName)
	b.WriteString(")\n\n")
	// handleName is the wrapper's embedded field: an unexported alias for
	// rasql.Table[row], so the wrapper's own Ref, As and CatalogObject methods
	// stay promoted from it while the field itself stays out of the package's
	// exported surface. An alias field keeps the exact type rasql.Table[row]
	// is, so promotion reaches the same unexported methods (Relation,
	// RowSource) a directly embedded rasql.Table[row] would give.
	handleName := compactLowerFirst(accessor) + "TableHandle"
	b.WriteString("type ")
	b.WriteString(handleName)
	b.WriteString(" = rasql.Table[")
	b.WriteString(row)
	b.WriteString("]\n\n")
	b.WriteString("type ")
	b.WriteString(accessor)
	b.WriteString("Table struct {\n\t")
	b.WriteString(handleName)
	b.WriteString("\n\t")
	b.WriteString(accessor)
	b.WriteString("Expressions\n}\n\n")
	// The wrapper carries its own columns, so a caller writes t.ID rather
	// than binding a separate value first. Every constructor below rebuilds
	// them, because a column reference holds the alias and namespace of the
	// table it was bound against, and As and InSchema each return a table
	// carrying a different one.
	b.WriteString("func new")
	b.WriteString(accessor)
	b.WriteString("Table(handle ")
	b.WriteString(handleName)
	b.WriteString(") ")
	b.WriteString(accessor)
	b.WriteString("Table {\n\treturn ")
	b.WriteString(accessor)
	b.WriteString("Table{")
	b.WriteString(handleName)
	b.WriteString(": handle, ")
	b.WriteString(accessor)
	b.WriteString("Expressions: bind")
	b.WriteString(accessor)
	b.WriteString("Expressions(handle)}\n}\n\n")
	b.WriteString("func ")
	b.WriteString(accessor)
	b.WriteString("() ")
	b.WriteString(accessor)
	b.WriteString("Table { return new")
	b.WriteString(accessor)
	b.WriteString("Table(")
	b.WriteString(tableName)
	b.WriteString(") }\n\n")
	b.WriteString("func (t ")
	b.WriteString(accessor)
	b.WriteString("Table) Ref() query.TableRef { return t.")
	b.WriteString(handleName)
	b.WriteString(".Ref() }\n\n")
	b.WriteString("func (t ")
	b.WriteString(accessor)
	b.WriteString("Table) As(alias string) (")
	b.WriteString(accessor)
	b.WriteString("Table, error) {\n\taliased, err := t.")
	b.WriteString(handleName)
	b.WriteString(".As(alias)\n\tif err != nil {\n\t\treturn ")
	b.WriteString(accessor)
	b.WriteString("Table{}, err\n\t}\n\treturn new")
	b.WriteString(accessor)
	b.WriteString("Table(aliased), nil\n}\n\n")
	b.WriteString("func (t ")
	b.WriteString(accessor)
	b.WriteString("Table) InSchema(namespace string) (")
	b.WriteString(accessor)
	b.WriteString("Table, error) {\n\tmoved, err := t.")
	b.WriteString(handleName)
	b.WriteString(".InSchema(namespace)\n\tif err != nil {\n\t\treturn ")
	b.WriteString(accessor)
	b.WriteString("Table{}, err\n\t}\n\treturn new")
	b.WriteString(accessor)
	b.WriteString("Table(moved), nil\n}\n\n")
	// The wrapper keeps its rasql.Table in an unexported field, so nothing
	// outside this package could otherwise hand one to rasql.NewCreatePlan,
	// rasql.NewPatchPlan or any other core constructor that takes the typed
	// table. This function is the way through. It is package-level rather
	// than a method because a method would be one more name a column of this
	// table could collide with, and the column that needs this function most
	// is exactly the one whose name already collided.
	b.WriteString("// ")
	b.WriteString(accessor)
	b.WriteString("Handle returns the typed table inside t, which the constructors in\n")
	b.WriteString("// the rasql package take: rasql.NewCreatePlan, rasql.NewPatchPlan and\n")
	b.WriteString("// rasql.NewDeletePlan. Reach for it to write a column whose builder setter\n")
	b.WriteString("// this package could not generate.\n")
	b.WriteString("func ")
	b.WriteString(accessor)
	b.WriteString("Handle(t ")
	b.WriteString(accessor)
	b.WriteString("Table) rasql.Table[")
	b.WriteString(row)
	b.WriteString("] { return t.")
	b.WriteString(handleName)
	b.WriteString(" }\n\n")

	writeCompactColumns(&b, object, omissions, accessor, row)
	writeCompactDecoder(&b, object, omissions, accessor, row, false)
	marker := compactMarker(object.Table)
	if len(marker) > 0 {
		writeCompactDecoder(&b, object, omissions, accessor, row, true)
	}
	writeCompactProjections(&b, object, omissions, accessor, row, len(marker) > 0)
	writeCompactKeys(&b, object, omissions, accessor, row, marker)
	writeCompactRelations(&b, object, omissions, accessor, row)
	writeCompactMutations(&b, object, omissions, accessor, row, handleName)
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("compact %s: format source: %w", object.Catalog.ID, err)
	}
	return formatted, warnings, nil
}

type compactImport struct{ Path, Alias string }

type compactFieldGroup struct {
	Names []string
	Type  string
}

func appendCompactFieldGroup(groups []compactFieldGroup, name, typ string) []compactFieldGroup {
	if len(groups) > 0 && groups[len(groups)-1].Type == typ {
		groups[len(groups)-1].Names = append(groups[len(groups)-1].Names, name)
		return groups
	}
	return append(groups, compactFieldGroup{Names: []string{name}, Type: typ})
}

func compactFieldGroups(omissions compactOmissions, fields []compilerir.GoField) []compactFieldGroup {
	groups := make([]compactFieldGroup, 0, len(fields))
	for _, field := range fields {
		if omissions.SkipsColumn(field.Name) {
			continue
		}
		groups = appendCompactFieldGroup(groups, exportedCompact(field.Name), field.Type)
	}
	return groups
}

func compactImports(object CompactObject) []compactImport {
	seen := map[string]compactImport{}
	for _, column := range object.Go.Columns {
		if strings.Contains(column.GoType, "time.Time") {
			seen["time"] = compactImport{Path: "time"}
		}
		mapping, ok := compilerir.DefaultScalarMapping(column.Scalar)
		if !ok {
			for _, candidate := range object.Mappings {
				if candidate.Name == column.Scalar {
					mapping, ok = candidate, true
					break
				}
			}
		}
		if ok {
			for _, imp := range mapping.Imports {
				seen[imp.Path] = compactImport{Path: imp.Path, Alias: imp.Alias}
			}
		}
		if binding, ok := compilerir.ColumnGoBindingFor(object.Catalog.ID, column.Name, object.ColumnBindings); ok {
			for _, imp := range binding.Imports {
				seen[imp.Path] = compactImport{Path: imp.Path, Alias: imp.Alias}
			}
		}
	}
	result := make([]compactImport, 0, len(seen))
	for _, imp := range seen {
		if imp.Path == "github.com/lestrrat-go/rasql" || imp.Path == "github.com/lestrrat-go/rasql/query" || imp.Path == "github.com/lestrrat-go/rasql/schema" {
			continue
		}
		result = append(result, imp)
	}
	slicesSortImports(result)
	return result
}

func slicesSortImports(values []compactImport) {
	for i := 1; i < len(values); i++ {
		for j := i; j > 0 && values[j].Path < values[j-1].Path; j-- {
			values[j], values[j-1] = values[j-1], values[j]
		}
	}
}

func writeCompactColumns(b *bytes.Buffer, object CompactObject, omissions compactOmissions, accessor, row string) {
	b.WriteString("type ")
	b.WriteString(accessor)
	b.WriteString("Expressions struct {\n")
	groups := make([]compactFieldGroup, 0, len(object.Go.Columns))
	for _, column := range object.Go.Columns {
		if !columnReadable(object.Semantic, column.Name) || omissions.SkipsColumn(column.Name) {
			continue
		}
		typ := "rasql.Column[" + row + "," + compactColumnValueType(object, column) + "]"
		if column.Nullable {
			typ = "rasql.NullColumn[" + row + "," + compactColumnValueType(object, column) + "]"
		}
		groups = appendCompactFieldGroup(groups, exportedCompact(column.Name), typ)
	}
	for _, group := range groups {
		b.WriteString("\t")
		b.WriteString(strings.Join(group.Names, ", "))
		b.WriteByte(' ')
		b.WriteString(group.Type)
		b.WriteByte('\n')
	}
	b.WriteString("}\n\ntype Optional")
	b.WriteString(accessor)
	b.WriteString("Expressions struct {\n")
	groups = groups[:0]
	for _, column := range object.Go.Columns {
		if !columnReadable(object.Semantic, column.Name) || omissions.SkipsColumn(column.Name) {
			continue
		}
		groups = appendCompactFieldGroup(groups, exportedCompact(column.Name), "rasql.NullColumn["+row+","+compactColumnValueType(object, column)+"]")
	}
	for _, group := range groups {
		b.WriteString("\t")
		b.WriteString(strings.Join(group.Names, ", "))
		b.WriteByte(' ')
		b.WriteString(group.Type)
		b.WriteByte('\n')
	}
	b.WriteString("}\n\n")

	writeCompactBinder(b, object, omissions, accessor, row, false)
	writeCompactBinder(b, object, omissions, accessor, row, true)
}

// writeCompactBinder writes the function that names every column of one table.
//
// The non-optional form is the unexported constructor the wrapper's own Table
// accessor, As and InSchema each call, so the columns a caller reads as fields
// carry whatever alias or namespace that particular table value holds. The
// optional form is a method on the wrapper, because an outer join's nullable
// side is asked for one appearance at a time.
//
// Neither reports an error. rasqlgenColumn in schema_gen.go states why.
func writeCompactBinder(b *bytes.Buffer, object CompactObject, omissions compactOmissions, accessor, row string, optional bool) {
	result := accessor + "Expressions"
	handle := compactLowerFirst(accessor) + "TableHandle"
	if optional {
		result = "Optional" + accessor + "Expressions"
		b.WriteString("// Optional names every column of t as it appears on the nullable side\n")
		b.WriteString("// of an outer join, where the whole row may be absent.\n")
		b.WriteString("func (t ")
		b.WriteString(accessor)
		b.WriteString("Table) Optional() ")
	} else {
		b.WriteString("func bind")
		b.WriteString(accessor)
		b.WriteString("Expressions(source ")
		b.WriteString(handle)
		b.WriteString(") ")
	}
	b.WriteString(result)
	b.WriteString(" {\n")
	if optional {
		b.WriteString("\tsource := rasql.Optional[")
		b.WriteString(row)
		b.WriteString("](t.")
		b.WriteString(handle)
		b.WriteString(")\n")
	}
	b.WriteString("\treturn ")
	b.WriteString(result)
	b.WriteString("{\n")
	for _, column := range object.Go.Columns {
		if !columnReadable(object.Semantic, column.Name) || omissions.SkipsColumn(column.Name) {
			continue
		}
		b.WriteString("\t\t")
		b.WriteString(exportedCompact(column.Name))
		b.WriteString(": rasqlgenColumn(source, ")
		b.WriteString(strconv.Quote(column.PhysicalName))
		b.WriteString(", ")
		b.WriteString(strconv.Quote(column.Codec))
		b.WriteString(", rasql.")
		if optional {
			b.WriteString("BindOptionalColumn[")
		} else if column.Nullable {
			b.WriteString("BindNullColumn[")
		} else {
			b.WriteString("BindColumn[")
		}
		b.WriteString(row)
		b.WriteByte(',')
		b.WriteString(compactColumnValueType(object, column))
		b.WriteString("]),\n")
	}
	b.WriteString("\t}\n}\n\n")
}

func writeCompactDecoder(b *bytes.Buffer, object CompactObject, omissions compactOmissions, accessor, row string, optional bool) {
	name := compactLowerFirst(accessor) + "Decoder"
	if optional {
		name = compactLowerFirst(accessor) + "OptionalDecoder"
	}
	schemaName := compactLowerFirst(accessor) + "ResultSchema"
	if optional {
		schemaName = compactLowerFirst(accessor) + "OptionalResultSchema"
	}
	baseColumnsName := compactLowerFirst(accessor) + "ResultColumns"
	if !optional {
		b.WriteString("var ")
		b.WriteString(baseColumnsName)
		b.WriteString(" = []rasql.ResultColumn{\n")
		for _, column := range object.Go.Columns {
			if !columnReadable(object.Semantic, column.Name) || omissions.SkipsColumn(column.Name) {
				continue
			}
			b.WriteString("\t{Name: ")
			b.WriteString(strconv.Quote(column.PhysicalName))
			b.WriteString(", Type: ")
			b.WriteString(compactSchemaType(object.Table, column.PhysicalName))
			if column.Nullable {
				b.WriteString(", Nullable: true")
			}
			b.WriteString(", Codec: ")
			b.WriteString(strconv.Quote(column.Codec))
			b.WriteString("},\n")
		}
		b.WriteString("}\n")
		b.WriteString("var ")
		b.WriteString(schemaName)
		b.WriteString(" = rasqlgenResultSchema(")
		b.WriteString(baseColumnsName)
		b.WriteString(")\n\n")
	} else {
		b.WriteString("var ")
		b.WriteString(schemaName)
		b.WriteString(" = rasqlgenOptionalResultSchema(")
		b.WriteString(baseColumnsName)
		b.WriteString(")\n\n")
	}
	b.WriteString("type ")
	b.WriteString(name)
	b.WriteString(" struct{}\nfunc (")
	b.WriteString(name)
	b.WriteString(") ResultSchema() rasql.ResultSchema { return ")
	b.WriteString(schemaName)
	b.WriteString(" }\nfunc (")
	b.WriteString(name)
	b.WriteString(") Presence() []rasql.Presence {")
	if optional {
		marker := compactMarker(object.Table)
		b.WriteString(" p, err := rasql.NewPresence(")
		b.WriteString(strconv.Quote(accessor))
		for _, column := range marker {
			b.WriteString(", ")
			b.WriteString(strconv.Quote(column))
		}
		b.WriteString("); if err != nil { panic(err) }; return []rasql.Presence{p}")
	} else {
		b.WriteString(" return nil")
	}
	b.WriteString(" }\n")
	b.WriteString("func (")
	b.WriteString(name)
	b.WriteString(") DecodeRow(source rasql.ScanSource, row *")
	b.WriteString(row)
	b.WriteString(") error {\n")
	if optional {
		valueGroups := make([]compactFieldGroup, 0, len(object.Go.Columns))
		for _, column := range object.Go.Columns {
			if !columnReadable(object.Semantic, column.Name) || omissions.SkipsColumn(column.Name) {
				continue
			}
			if compactNullableDirect(object, column) {
				continue
			}
			valueGroups = appendCompactFieldGroup(valueGroups, exportedCompact(column.Name)+"Value", "rasql.Nullable["+compactColumnValueType(object, column)+"]")
		}
		for _, group := range valueGroups {
			b.WriteString("\tvar ")
			b.WriteString(strings.Join(group.Names, ", "))
			b.WriteByte(' ')
			b.WriteString(group.Type)
			b.WriteByte('\n')
		}
	}
	if optional {
		b.WriteString("\tif err := source.Scan(")
	} else {
		b.WriteString("\treturn source.Scan(")
	}
	first := true
	for _, column := range object.Go.Columns {
		if !columnReadable(object.Semantic, column.Name) || omissions.SkipsColumn(column.Name) {
			continue
		}
		if !first {
			b.WriteString(", ")
		}
		first = false
		if optional {
			b.WriteString("&")
			if compactNullableDirect(object, column) {
				b.WriteString("row.")
				b.WriteString(exportedCompact(column.Name))
			} else {
				b.WriteString(exportedCompact(column.Name))
				b.WriteString("Value")
			}
		} else {
			b.WriteString("&row.")
			b.WriteString(exportedCompact(column.Name))
		}
	}
	if optional {
		b.WriteString("); err != nil { return err }\n")
	} else {
		b.WriteString(")\n}\n\n")
		// A column of this table is named ScanRow, and Go allows a type one
		// member of that name. The column is the caller's and this method is
		// only a convenience over the decoder above, which nothing inside
		// rasql reaches through the row, so the column keeps the name.
		if !omissions.ScanRow {
			b.WriteString("func (row *")
			b.WriteString(row)
			b.WriteString(") ScanRow(source rasql.ScanSource) error { return ")
			b.WriteString(name)
			b.WriteString("{}.DecodeRow(source, row) }\n\n")
		}
		return
	}
	if optional {
		for _, column := range object.Go.Columns {
			if !columnReadable(object.Semantic, column.Name) || omissions.SkipsColumn(column.Name) {
				continue
			}
			if compactNullableDirect(object, column) {
				continue
			}
			b.WriteString("\trasqlgenAssignNullable(")
			b.WriteString(exportedCompact(column.Name))
			b.WriteString("Value, &row.")
			b.WriteString(exportedCompact(column.Name))
			b.WriteString(")\n")
		}
	}
	b.WriteString("\treturn nil\n}\n\n")
}

func writeCompactProjections(b *bytes.Buffer, object CompactObject, omissions compactOmissions, accessor, row string, optional bool) {
	writeProjection := func(name string, optionalProjection bool) {
		b.WriteString("func ")
		b.WriteString(name)
		b.WriteString("(source ")
		if optionalProjection {
			b.WriteString("Optional")
			b.WriteString(accessor)
			b.WriteString("Expressions")
		} else {
			// The table carries its own columns, so the caller passes the
			// table itself rather than a value bound from it first.
			b.WriteString(accessor)
			b.WriteString("Table")
		}
		b.WriteString(") (rasql.Projection[")
		b.WriteString(row)
		b.WriteString("], error) {\n\titems := []rasql.ProjectionItem{\n")
		for _, column := range object.Go.Columns {
			if !columnReadable(object.Semantic, column.Name) || omissions.SkipsColumn(column.Name) {
				continue
			}
			field := exportedCompact(column.Name)
			b.WriteString("\t\t")
			if optionalProjection || column.Nullable {
				b.WriteString("rasql.NullItem(")
			} else {
				b.WriteString("rasql.Item(")
			}
			b.WriteString(strconv.Quote(column.PhysicalName))
			b.WriteString(", ")
			selector := compactColumnSelector("source", accessor, field)
			if optionalProjection {
				selector = "source." + field
			}
			b.WriteString(selector)
			if optionalProjection || column.Nullable {
				b.WriteString(".NullExpr()")
			} else {
				b.WriteString(".Expr()")
			}
			b.WriteString(", ")
			b.WriteString(compactSchemaType(object.Table, column.PhysicalName))
			b.WriteString(", ")
			b.WriteString(strconv.Quote(column.Codec))
			b.WriteString("),\n")
		}
		b.WriteString("\t}\n\treturn rasql.NewProjection(items, ")
		if optionalProjection {
			b.WriteString(compactLowerFirst(accessor) + "OptionalDecoder{}")
		} else {
			b.WriteString(compactLowerFirst(accessor) + "Decoder{}")
		}
		b.WriteString(")\n}\n\n")
	}
	writeProjection(accessor+"Projection", false)
	if optional {
		writeProjection("Optional"+accessor+"Projection", true)
	}
}

func compactPageColumns(object CompactObject, omissions compactOmissions) []compilerir.GoColumn {
	result := make([]compilerir.GoColumn, 0, len(object.Go.Columns))
	for _, column := range object.Go.Columns {
		if omissions.SkipsColumn(column.Name) {
			continue
		}
		if columnReadable(object.Semantic, column.Name) && compactPlainNullableRowType(object, column) {
			result = append(result, column)
		}
	}
	return result
}

// compactPlainNullableRowType reports whether a nullable column's row field
// is exactly rasql.Nullable[T] for its own value type T -- the shape every
// "func(row R) rasql.Nullable[T] { return row.Field }" this file writes
// requires, since a function literal's return statement needs an identical
// type, not merely a convertible one. It is true unconditionally for a
// non-nullable column, which no such closure is ever written for.
//
// A ScalarMapping's NullableGoType (compactCustomNullable already names this
// case) or a column's GoBinding can each choose a different, self-contained
// shape for a nullable column -- GoBinding's own default is a bare pointer --
// and a column in either state fails this check.
func compactPlainNullableRowType(object CompactObject, column compilerir.GoColumn) bool {
	if !column.Nullable {
		return true
	}
	if compactCustomNullable(object, column) {
		return false
	}
	if _, ok := compilerir.ColumnGoBindingFor(object.Catalog.ID, column.Name, object.ColumnBindings); ok {
		return column.GoType == "rasql.Nullable["+compactColumnValueType(object, column)+"]"
	}
	return true
}

func compactRelations(object CompactObject) []compilerir.GoRelation {
	result := make([]compilerir.GoRelation, 0, len(object.Go.Relations))
	for _, relation := range object.Go.Relations {
		if _, ok := object.Targets[relation.Target]; ok {
			result = append(result, relation)
		}
	}
	return result
}

func writeCompactKeys(b *bytes.Buffer, object CompactObject, omissions compactOmissions, accessor, row string, marker []string) {
	if len(marker) > 0 {
		b.WriteString("func ")
		b.WriteString(accessor)
		b.WriteString("GraphKey(source ")
		b.WriteString(accessor)
		b.WriteString("Table) (rasql.GraphKey[")
		b.WriteString(row)
		b.WriteString("], error) {\n\treturn rasql.NewGraphKey[")
		b.WriteString(row)
		b.WriteString("](")
		writeCompactGraphParts(b, object, omissions, accessor, row, marker, "source")
		b.WriteString(")\n}\n\n")
	}
	for _, column := range compactPageColumns(object, omissions) {
		field := exportedCompact(column.Name)
		valueType := compactColumnValueType(object, column)
		b.WriteString("func ")
		b.WriteString(accessor)
		b.WriteString(field)
		b.WriteString("PageKey(source ")
		b.WriteString(accessor)
		b.WriteString("Table, direction rasql.PageDirection")
		if column.Nullable {
			b.WriteString(", nulls rasql.NullOrder")
		}
		b.WriteString(") (rasql.PageKey[")
		b.WriteString(row)
		b.WriteString("], error) {\n\treturn rasqlgen")
		if column.Nullable {
			b.WriteString("NullablePageKey(direction, ")
		} else {
			b.WriteString("PageKey(direction, ")
		}
		b.WriteString(compactColumnSelector("source", accessor, field))
		if column.Nullable {
			b.WriteString(".NullExpr(), func(row ")
			b.WriteString(row)
			b.WriteString(") rasql.Nullable[")
			b.WriteString(valueType)
			b.WriteString("] { return row.")
			b.WriteString(field)
			b.WriteString(" }, nulls)")
		} else {
			b.WriteString(".Expr(), func(row ")
			b.WriteString(row)
			b.WriteString(") ")
			b.WriteString(valueType)
			b.WriteString(" { return row.")
			b.WriteString(field)
			b.WriteString(" })")
		}
		b.WriteString("\n}\n\n")
	}
}

func writeCompactGraphParts(b *bytes.Buffer, object CompactObject, omissions compactOmissions, accessor, row string, columns []string, source string) {
	for i, name := range columns {
		if i > 0 {
			b.WriteString(", ")
		}
		column, ok := goColumnByName(object.Go, name)
		if !ok || omissions.SkipsColumn(name) || !compactPlainNullableRowType(object, column) {
			// A column whose nullable row field is not itself
			// rasql.Nullable[T] cannot be returned from the
			// "func(row R) rasql.Nullable[T]" this function otherwise
			// writes below, the same reason compactPageColumns excludes
			// it from PageKey generation. There is no positional way to
			// omit one key part, so this falls back to the same
			// placeholder an unmatched column already uses.
			b.WriteString("rasql.GraphKeyPart[")
			b.WriteString(row)
			b.WriteString("]{}")
			continue
		}
		field := exportedCompact(name)
		valueType := compactColumnValueType(object, column)
		if column.Nullable {
			b.WriteString("rasql.NullKeyPart[")
		} else {
			b.WriteString("rasql.KeyPart[")
		}
		b.WriteString(row)
		b.WriteByte(',')
		b.WriteString(valueType)
		b.WriteString("](")
		b.WriteString(compactColumnSelector(source, accessor, field))
		if column.Nullable {
			b.WriteString(", func(row ")
			b.WriteString(row)
			b.WriteString(") rasql.Nullable[")
			b.WriteString(valueType)
			b.WriteString("] { return row.")
			b.WriteString(field)
			b.WriteString(" })")
		} else {
			b.WriteString(", func(row ")
			b.WriteString(row)
			b.WriteString(") ")
			b.WriteString(valueType)
			b.WriteString(" { return row.")
			b.WriteString(field)
			b.WriteString(" })")
		}
	}
}

func writeCompactRelations(b *bytes.Buffer, object CompactObject, omissions compactOmissions, accessor, row string) {
	for _, relation := range compactRelations(object) {
		target := object.Targets[relation.Target]
		targetAccessor := target.Generation.Source
		if targetAccessor == "" {
			targetAccessor = exportedCompact(target.Catalog.Name)
		}
		targetRow := target.Generation.Row
		if targetRow == "" {
			targetRow = exportedCompact(target.Catalog.Name) + "Row"
		}
		name := accessor + compilerir.RelationGoName(relation.Name) + "Edge"
		b.WriteString("func ")
		b.WriteString(name)
		b.WriteString("[G, CG any](parentSource ")
		b.WriteString(accessor)
		b.WriteString("Table, ")
		if relation.Kind == "many_through" && relation.Through != nil {
			through := object.Targets[relation.Through.Object]
			throughAccessor := through.Generation.Source
			if throughAccessor == "" {
				throughAccessor = exportedCompact(through.Catalog.Name)
			}
			b.WriteString("junctionSource ")
			b.WriteString(throughAccessor)
			b.WriteString("Table, ")
		}
		b.WriteString("childSource ")
		b.WriteString(targetAccessor)
		b.WriteString("Table, children rasql.GraphPlan[")
		b.WriteString(targetRow)
		b.WriteString(", CG], options rasql.EdgeOptions, attach func(*G, rasql.Loaded")
		if relation.Kind == "belongs_to" || relation.Kind == "has_one" {
			b.WriteString("One[")
		} else {
			b.WriteString("Many[")
		}
		b.WriteString("CG])) (rasql.GraphEdge[")
		b.WriteString(row)
		b.WriteString(", G], error) {\n")
		b.WriteString("\tparent, err := rasql.NewGraphKey[")
		b.WriteString(row)
		b.WriteString("](")
		writeCompactGraphParts(b, object, omissions, accessor, row, relation.From, "parentSource")
		b.WriteString(")\n\tif err != nil { return nil, err }\n")
		if relation.Kind == "many_through" && relation.Through != nil {
			through, ok := object.Targets[relation.Through.Object]
			if !ok {
				continue
			}
			throughAccessor := through.Generation.Source
			if throughAccessor == "" {
				throughAccessor = exportedCompact(through.Catalog.Name)
			}
			throughRow := through.Generation.Row
			if throughRow == "" {
				throughRow = exportedCompact(through.Catalog.Name) + "Row"
			}
			b.WriteString("\tjunctionParent, err := rasql.NewGraphKey[")
			b.WriteString(throughRow)
			b.WriteString("](")
			writeCompactGraphParts(b, compactTargetObject(through, object), compactTargetOmissions(through, object), throughAccessor, throughRow, relation.Through.SourceFrom, "junctionSource")
			b.WriteString(")\n\tif err != nil { return nil, err }\n")
			b.WriteString("\tjunctionChild, err := rasql.NewGraphKey[")
			b.WriteString(throughRow)
			b.WriteString("](")
			writeCompactGraphParts(b, compactTargetObject(through, object), compactTargetOmissions(through, object), throughAccessor, throughRow, relation.Through.TargetFrom, "junctionSource")
			b.WriteString(")\n\tif err != nil { return nil, err }\n")
			b.WriteString("\tchild, err := rasql.NewGraphKey[")
			b.WriteString(targetRow)
			b.WriteString("](")
			writeCompactGraphParts(b, compactTargetObject(target, object), compactTargetOmissions(target, object), targetAccessor, targetRow, relation.To, "childSource")
			b.WriteString(")\n\tif err != nil { return nil, err }\n")
			b.WriteString("\treturn rasql.ManyThrough(\"")
			b.WriteString(relation.Name)
			b.WriteString("\", parent, junctionParent, junctionChild, child, junctionSource, children, options, attach)\n}\n\n")
			continue
		}
		b.WriteString("\tchild, err := rasql.NewGraphKey[")
		b.WriteString(targetRow)
		b.WriteString("](")
		writeCompactGraphParts(b, compactTargetObject(target, object), compactTargetOmissions(target, object), targetAccessor, targetRow, relation.To, "childSource")
		b.WriteString(")\n\tif err != nil { return nil, err }\n\treturn rasql.")
		if relation.Kind == "belongs_to" || relation.Kind == "has_one" {
			b.WriteString("HasOne")
		} else {
			b.WriteString("HasMany")
		}
		b.WriteString("(\"")
		b.WriteString(relation.Name)
		b.WriteString("\", parent, child, children, options, attach)\n}\n\n")
	}
}

// writeCompactMutations writes the mutation builder for each row write the
// descriptor permits: a create builder for schema.OperationInsert, a patch
// builder for schema.OperationUpdate, and a delete builder for
// schema.OperationDelete. A view permits none of the three and gets none,
// which is what the Kind test this replaced already produced, and a
// descriptor naming only some of the writes now gets only the builders for
// those.
//
// Each builder stores the table its Create, Patch or Delete method was called
// on, so Plan and Exec write through that table -- including one InSchema
// moved to a different namespace -- rather than through the package-level
// accessor.
//
// Every builder carries both a Plan method, which stays the documented escape
// hatch for rasql.ExecBatch and for rendering a statement without running it,
// and a terminal Exec method, which builds the plan and runs it in one call so
// the common path costs one error check instead of two.
//
// An object permitting neither insert nor update skips the shared
// mutation-columns variable too, since nothing left in the file reads it.
func writeCompactMutations(b *bytes.Buffer, object CompactObject, omissions compactOmissions, accessor, row, handleName string) {
	insert := object.Table.Supports(schema.OperationInsert)
	update := object.Table.Supports(schema.OperationUpdate)
	remove := object.Table.Supports(schema.OperationDelete)
	if insert || update {
		create := object.Generation.Create
		patch := object.Generation.Patch
		if create == "" {
			create = accessor + "Create"
		}
		if patch == "" {
			patch = accessor + "Patch"
		}
		mutationColumns := compactLowerFirst(accessor) + "MutationColumns"
		b.WriteString("var ")
		b.WriteString(mutationColumns)
		b.WriteString(" = bind")
		b.WriteString(accessor)
		b.WriteString("Expressions(")
		b.WriteString(compactLowerFirst(accessor))
		b.WriteString("Table)\n\n")
		if insert {
			writeMutationType(b, object, omissions, row, create, false, mutationColumns)
			b.WriteString("func (t ")
			b.WriteString(accessor)
			b.WriteString("Table) Create() ")
			b.WriteString(create)
			b.WriteString(" { return ")
			b.WriteString(create)
			b.WriteString("{table: t.")
			b.WriteString(handleName)
			b.WriteString("} }\n\n")
		}
		if update {
			writeMutationType(b, object, omissions, row, patch, true, mutationColumns)
			b.WriteString("func (t ")
			b.WriteString(accessor)
			b.WriteString("Table) Patch() ")
			b.WriteString(patch)
			b.WriteString(" { return ")
			b.WriteString(patch)
			b.WriteString("{table: t.")
			b.WriteString(handleName)
			b.WriteString("} }\n\n")
		}
	}
	if remove {
		writeCompactDeleteBuilder(b, object, accessor, row, handleName)
	}
}

// writeCompactDeleteBuilder writes the delete builder for one object: the
// table's Delete method, which takes no argument and hands back the builder,
// and the builder's own Where, Plan and Exec. Where stores the predicate and
// returns the builder rather than building the plan immediately, matching the
// patch builder's shape; Plan and Exec both call rasql.NewDeletePlan once the
// predicate is in hand.
func writeCompactDeleteBuilder(b *bytes.Buffer, object CompactObject, accessor, row, handleName string) {
	name := accessor + "Delete"
	b.WriteString("type ")
	b.WriteString(name)
	b.WriteString(" struct {\n\ttable rasql.Table[")
	b.WriteString(row)
	b.WriteString("]\n\twhere rasql.Predicate\n}\n\n")
	b.WriteString("func (t ")
	b.WriteString(accessor)
	b.WriteString("Table) Delete() ")
	b.WriteString(name)
	b.WriteString(" { return ")
	b.WriteString(name)
	b.WriteString("{table: t.")
	b.WriteString(handleName)
	b.WriteString("} }\n\n")
	b.WriteString("func (v ")
	b.WriteString(name)
	b.WriteString(") Where(value rasql.Predicate) ")
	b.WriteString(name)
	b.WriteString(" { v.where = value; return v }\n\n")
	b.WriteString("func (v ")
	b.WriteString(name)
	b.WriteString(") Plan() (rasql.DeletePlan[")
	b.WriteString(row)
	b.WriteString("], error) { return rasql.NewDeletePlan(v.table, v.where) }\n\n")
	b.WriteString("func (v ")
	b.WriteString(name)
	b.WriteString(") Exec(ctx context.Context, executor rasql.Executor) (rasql.MutationOutcome, error) {\n")
	b.WriteString("\tplan, err := v.Plan()\n\tif err != nil {\n\t\treturn rasql.MutationOutcome{}, err\n\t}\n")
	b.WriteString("\treturn rasql.Exec(ctx, executor, plan)\n}\n\n")
}

func writeMutationType(b *bytes.Buffer, object CompactObject, omissions compactOmissions, row, name string, patch bool, mutationColumns string) {
	b.WriteString("type ")
	b.WriteString(name)
	b.WriteString(" struct {\n\ttable  rasql.Table[")
	b.WriteString(row)
	b.WriteString("]\n\tfields []rasql.MutationField[")
	b.WriteString(row)
	b.WriteString("]\n")
	if patch {
		b.WriteString("\twhere  rasql.Predicate\n")
	}
	b.WriteString("}\n")
	shape := object.Go.Create
	if patch {
		shape = object.Go.Patch
	}
	if shape != nil {
		for _, field := range shape.Fields {
			column, ok := goColumnByName(object.Go, field.Name)
			if !ok {
				continue
			}
			// A setter is left out where its name is this builder's own
			// terminal, or where an earlier column's Clear or Default setter
			// took it. The column is still read and still written, through
			// rasql.SetField against the column field on the table.
			skipSetter := omissions.SkipsCreateSetter(field.Name)
			if patch {
				skipSetter = omissions.SkipsPatchSetter(field.Name)
			}
			method := exportedCompact(field.Name)
			if skipSetter {
				writeMutationSetterNote(b, name, method, field.Name)
			} else {
				writeMutationSetter(b, object, column, name, method, mutationColumns)
			}
			if column.Nullable && !omissions.SkipsClearSetter(field.Name) {
				b.WriteString("func (v ")
				b.WriteString(name)
				b.WriteString(") Clear")
				b.WriteString(method)
				b.WriteString("() ")
				b.WriteString(name)
				b.WriteString(" { v.fields = rasqlgenAppendMutationField(v.fields, rasql.ClearField(")
				b.WriteString(mutationColumns)
				b.WriteByte('.')
				b.WriteString(method)
				b.WriteString(")); return v }\n")
			}
			if columnHasDefault(object.Table, field.Name) && !omissions.SkipsDefaultSetter(field.Name) {
				b.WriteString("func (v ")
				b.WriteString(name)
				b.WriteString(") Default")
				b.WriteString(method)
				b.WriteString("() ")
				b.WriteString(name)
				b.WriteString(" { v.fields = rasqlgenAppendMutationField(v.fields, ")
				if column.Nullable {
					b.WriteString("rasql.DefaultNullableField(")
				} else {
					b.WriteString("rasql.DefaultField(")
				}
				b.WriteString(mutationColumns)
				b.WriteByte('.')
				b.WriteString(method)
				b.WriteString(")); return v }\n")
			}
		}
	}
	if patch {
		b.WriteString("func (v ")
		b.WriteString(name)
		b.WriteString(") Where(value rasql.Predicate) ")
		b.WriteString(name)
		b.WriteString(" { v.where = value; return v }\n\n")
		b.WriteString("func (v ")
		b.WriteString(name)
		b.WriteString(") Plan() (rasql.PatchPlan[")
		b.WriteString(row)
		b.WriteString("], error) { return rasql.NewPatchPlan(v.table, v.where, v.fields...) }\n\n")
		b.WriteString("func (v ")
		b.WriteString(name)
		b.WriteString(") Exec(ctx context.Context, executor rasql.Executor) (rasql.MutationOutcome, error) {\n")
		b.WriteString("\tplan, err := v.Plan()\n\tif err != nil {\n\t\treturn rasql.MutationOutcome{}, err\n\t}\n")
		b.WriteString("\treturn rasql.Exec(ctx, executor, plan)\n}\n\n")
		return
	}
	b.WriteString("func (v ")
	b.WriteString(name)
	b.WriteString(") Plan() (rasql.CreatePlan[")
	b.WriteString(row)
	b.WriteString("], error) {\n")
	b.WriteString("\treturn rasql.NewCreatePlan(v.table, v.fields...)")
	b.WriteString("\n}\n\n")
	b.WriteString("func (v ")
	b.WriteString(name)
	b.WriteString(") Exec(ctx context.Context, executor rasql.Executor) (rasql.MutationOutcome, error) {\n")
	b.WriteString("\tplan, err := v.Plan()\n\tif err != nil {\n\t\treturn rasql.MutationOutcome{}, err\n\t}\n")
	b.WriteString("\treturn rasql.Exec(ctx, executor, plan)\n}\n\n")
}

func compactMarker(table schema.TableDef) []string {
	key := append([]string(nil), table.PrimaryKey...)
	if len(key) == 0 {
		for _, unique := range table.UniqueConstraints {
			if len(unique.Columns) == 0 {
				continue
			}
			valid := true
			for _, name := range unique.Columns {
				column, ok := table.Column(name)
				if !ok || column.Nullable {
					valid = false
					break
				}
			}
			if valid {
				key = append(key, unique.Columns...)
				break
			}
		}
	}
	for _, name := range key {
		column, ok := table.Column(name)
		if !ok || column.Nullable {
			return nil
		}
	}
	return key
}

func columnReadable(object compilerir.SemanticObject, name string) bool {
	for _, c := range object.Columns {
		if c.Name == name {
			return c.Readable
		}
	}
	return false
}
func goColumnByName(object compilerir.GoObject, name string) (compilerir.GoColumn, bool) {
	for _, c := range object.Columns {
		if c.Name == name {
			return c, true
		}
	}
	return compilerir.GoColumn{}, false
}
func columnHasDefault(table schema.TableDef, name string) bool {
	c, ok := table.Column(name)
	return ok && c.Default != ""
}
func compactLowerFirst(value string) string {
	if value == "" {
		return value
	}
	return strings.ToLower(value[:1]) + value[1:]
}
func exportedCompact(value string) string {
	var b strings.Builder
	upper := true
	for _, r := range value {
		if r == '_' || r == '-' || r == ' ' || r == '.' {
			upper = true
			continue
		}
		if upper {
			b.WriteString(strings.ToUpper(string(r)))
			upper = false
		} else {
			b.WriteRune(r)
		}
	}
	if b.Len() == 0 {
		return "Value"
	}
	result := b.String()
	for _, pair := range [][2]string{{"Id", "ID"}, {"Url", "URL"}, {"Uri", "URI"}, {"Api", "API"}} {
		if strings.HasSuffix(result, pair[0]) {
			result = strings.TrimSuffix(result, pair[0]) + pair[1]
		}
	}
	return result
}
func compactBaseType(value string) string {
	if strings.HasPrefix(value, "rasql.Nullable[") {
		return strings.TrimSuffix(strings.TrimPrefix(value, "rasql.Nullable["), "]")
	}
	return value
}
func compactColumnValueType(object CompactObject, column compilerir.GoColumn) string {
	for _, mapping := range object.Mappings {
		if mapping.Name == column.Scalar && mapping.GoType != "" {
			return mapping.GoType
		}
	}
	return compactBaseType(column.GoType)
}

func compactCustomNullable(object CompactObject, column compilerir.GoColumn) bool {
	if !column.Nullable {
		return false
	}
	for _, mapping := range object.Mappings {
		if mapping.Name == column.Scalar {
			return mapping.NullableGoType != "" && !strings.HasPrefix(mapping.NullableGoType, "rasql.Nullable[")
		}
	}
	return false
}

func compactNullableDirect(object CompactObject, column compilerir.GoColumn) bool {
	if compactCustomNullable(object, column) {
		return true
	}
	return column.Nullable && strings.HasPrefix(column.GoType, "rasql.Nullable[")
}

func compactSchemaType(table schema.TableDef, name string) string {
	var b bytes.Buffer
	column, _ := table.Column(name)
	writeColumnTypeLiteral(&b, column.Type)
	return b.String()
}

// writeMutationSetter writes one builder setter for one column.
func writeMutationSetter(b *bytes.Buffer, object CompactObject, column compilerir.GoColumn, name, method, mutationColumns string) {
	b.WriteString("func (v ")
	b.WriteString(name)
	b.WriteString(") ")
	b.WriteString(method)
	b.WriteString("(value ")
	b.WriteString(compactColumnValueType(object, column))
	b.WriteString(") ")
	b.WriteString(name)
	b.WriteString(" { v.fields = rasqlgenAppendMutationField(v.fields, ")
	if column.Nullable {
		b.WriteString("rasql.SetNullableField(")
	} else {
		b.WriteString("rasql.SetField(")
	}
	b.WriteString(mutationColumns)
	b.WriteByte('.')
	b.WriteString(method)
	b.WriteString(", value)); return v }\n")
}

// writeMutationSetterNote writes, in place of a setter this builder cannot
// have, the comment telling a reader where the column went and how to write it.
func writeMutationSetterNote(b *bytes.Buffer, name, method, physical string) {
	b.WriteString("\n// ")
	b.WriteString(name)
	b.WriteString(" has no ")
	b.WriteString(method)
	b.WriteString(" setter: that name is already this builder's own. Write the\n")
	b.WriteString("// ")
	b.WriteString(strconv.Quote(physical))
	b.WriteString(" column with rasql.SetField against the column field on the table,\n")
	b.WriteString("// which rasql.NewCreatePlan and rasql.NewPatchPlan both take.\n\n")
}
