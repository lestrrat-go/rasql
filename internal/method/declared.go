// Package method reports where a type's method is written, so a mapping method a
// type declares can be told apart from one Go promotes from an embedded field.
// The write direction needs that distinction: a promoted method maps only the
// embedded fields and knows nothing about the fields declared around them.
package method

import (
	"fmt"
	"reflect"
	"runtime"
	"strings"
)

// generatedFile is the file name the Go toolchain reports for a method it
// generates rather than one a package declares, such as the wrapper that
// promotes an embedded field's method to the outer struct.
//
// This name is the only signal that separates a promoted method from a declared
// one. The two are indistinguishable everywhere else reflect can look: they
// occupy the same slot of the same method set, the wrapper is named after the
// outer type just as a declared method is, and its code pointer is its own
// rather than the embedded method's. It is a property of the toolchain rather
// than of the language, so the callers state it for every shape their mapping
// rules rest on -- see TestGeneratedMethodsReportGeneratedFile in the rasql
// package -- and originOf refuses to guess when a build reports something else.
const generatedFile = "<autogenerated>"

// origin says where the implementation behind a method came from.
type origin int

const (
	// originNone means the type has no such method at all.
	originNone origin = iota
	// originDeclared means a package declares the method in a source file.
	originDeclared
	// originGenerated means the toolchain generated the method: either the
	// wrapper that promotes an embedded field's method, or the pointer type's
	// copy of a value-receiver method.
	originGenerated
	// originUnknown means the toolchain reported neither, so this build cannot
	// tell a declared method from a generated one.
	originUnknown
)

// Declared reports whether rowType declares the named method itself rather than
// promoting it from an embedded field. Both rowType and its pointer are asked,
// because a value receiver is declared on the value type and a pointer receiver
// on the pointer type, and the pointer type's copy of a value-receiver method is
// generated just as a promoted one is, so only the pair of answers separates the
// two cases. A build that reports an origin for neither is an error rather than a
// guess: guessing routes a row type by the wrong mapping and binds the wrong
// values silently, and an error says so.
func Declared(rowType reflect.Type, name string) (bool, error) {
	for _, methodType := range []reflect.Type{rowType, reflect.PointerTo(rowType)} {
		found, file := originOf(methodType, name)
		if found == originDeclared {
			return true, nil
		}
		if found == originUnknown {
			return false, fmt.Errorf("cannot tell whether %s declares %s or promotes it from an embedded field: this Go build reports %q as the file of the method, and rasql reads only a source file name (declared) or %q (generated)", methodType, name, file, generatedFile)
		}
	}
	return false, nil
}

// originOf reports where the named method of methodType came from, along with
// the file name the answer was read from.
func originOf(methodType reflect.Type, name string) (origin, string) {
	found, ok := methodType.MethodByName(name)
	if !ok {
		return originNone, ""
	}
	function := runtime.FuncForPC(found.Func.Pointer())
	if function == nil {
		return originUnknown, ""
	}
	file, _ := function.FileLine(found.Func.Pointer())
	return originForFile(file), file
}

// originForFile classifies the file name a build reports for a method. A
// generated method is reported as generatedFile and a declared one as the path
// of the file holding it. Anything else -- no name at all, the "?" the runtime
// reports when it has no line table, or another placeholder written in angle
// brackets -- is a name this package was not written against.
func originForFile(file string) origin {
	if file == generatedFile {
		return originGenerated
	}
	if file == "" || file == "?" || strings.HasPrefix(file, "<") {
		return originUnknown
	}
	return originDeclared
}
