// TestCompactGenerateScratchQueryConsumer proves the compact emitter's output for a file-backed
// query compiles and runs against a real SQLite database as its own module, and that a rerun of
// generate -scratch, and the offline check after it, both leave that output byte-identical.
func TestCompactGenerateScratchQueryConsumer(t *testing.T) {
	fixture := newCompactWorkflowFixture(t, "user_by_id_gen.go")
	var output, diagnostics bytes.Buffer
	command := fixture.command(t, &output, &diagnostics)

	require.NoError(t, command.run([]string{"generate", "-config", fixture.configPath, "-scratch"}), diagnostics.String())
	onlineFiles := snapshotGeneratedFiles(t, fixture.root)
	require.Contains(t, sortedFileNames(onlineFiles), "internal/store/user_by_id_gen.go")
	querySource := string(onlineFiles["internal/store/user_by_id_gen.go"])
	require.Contains(t, querySource, "func UserByID(id int64)")
	require.Contains(t, querySource, "type user_by_idResult struct")

	writeCompactConsumerModule(t, fixture.root)
	runCompactConsumer(t, fixture.root)

	output.Reset()
	diagnostics.Reset()
	require.NoError(t, command.run([]string{"generate", "-config", fixture.configPath, "-scratch"}), diagnostics.String())
	require.Equal(t, onlineFiles, snapshotGeneratedFiles(t, fixture.root))

	output.Reset()
	diagnostics.Reset()
	require.NoError(t, command.run([]string{"check", "-config", fixture.configPath}), diagnostics.String())
	require.Equal(t, onlineFiles, snapshotGeneratedFiles(t, fixture.root))
}

func TestCompactTypedQueryPlanOwnsExistingFiles(t *testing.T) {
	fixture := newCompactWorkflowFixture(t, "user_by_id_gen.go")
	var output, diagnostics bytes.Buffer
	command := fixture.command(t, &output, &diagnostics)
	require.NoError(t, command.run([]string{"generate", "-config", fixture.configPath, "-scratch"}), diagnostics.String())

	queryPath := filepath.Join(fixture.root, "internal", "store", "user_by_id_gen.go")
	queryBytes := workflowRead(t, queryPath)
	require.NoError(t, os.WriteFile(queryPath, append(queryBytes, []byte("\n// stale\n")...), 0o600))
	output.Reset()
	diagnostics.Reset()
	err := command.run([]string{"check", "-config", fixture.configPath})
	require.ErrorIs(t, err, generate.ErrStale)
	require.Equal(t, append(queryBytes, []byte("\n// stale\n")...), workflowRead(t, queryPath))

	require.NoError(t, os.WriteFile(queryPath, queryBytes, 0o600))
	// rasql.sum already records every file the last generate wrote, so that recorded set is
	// itself the ownership record: the offline check lists the output directory, and a
	// marker-carrying file absent from rasql.sum's own names is exactly the "outputs" difference
	// gensum.Compare already reports for a missing or changed one -- no database or rebuilt plan
	// is needed to catch it.
	orphanPath := filepath.Join(fixture.root, "internal", "store", "old_gen.go")
	require.NoError(t, os.WriteFile(orphanPath, []byte("// Code generated by rasqlgen; DO NOT EDIT.\n\npackage store\n"), 0o600))
	output.Reset()
	diagnostics.Reset()
	err = command.run([]string{"check", "-config", fixture.configPath})
	require.ErrorIs(t, err, generate.ErrStale)
	require.Contains(t, err.Error(), "outputs")
	require.Contains(t, err.Error(), "old_gen.go")
	require.FileExists(t, orphanPath)

	output.Reset()
	diagnostics.Reset()
	require.NoError(t, command.run([]string{"generate", "-config", fixture.configPath, "-scratch"}), diagnostics.String())
	require.NoFileExists(t, orphanPath)

	// A hand-written neighbour with no marker is invisible to the offline check: it is not
	// rasqlgen's to report on, unlike old_gen.go above.
	foreignPath := filepath.Join(fixture.root, "internal", "store", "foreign.go")
	require.NoError(t, os.WriteFile(foreignPath, []byte("package foreign\n"), 0o600))
	output.Reset()
	diagnostics.Reset()
	require.NoError(t, command.run([]string{"check", "-config", fixture.configPath}), diagnostics.String())

	beforeFiles := snapshotGeneratedFiles(t, fixture.root)
	output.Reset()
	diagnostics.Reset()
	err = command.run([]string{"generate", "-config", fixture.configPath, "-scratch"})
	require.Error(t, err)
	require.Contains(t, err.Error(), "foreign.go")
	require.Equal(t, beforeFiles, snapshotGeneratedFiles(t, fixture.root))
}

