package rasqlgen

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"strconv"

	"github.com/lestrrat-go/rasql/internal/sourcepkg"
	"github.com/lestrrat-go/rasql/schema"
)

// loadExistingDescriptionTables reads directory's own Tables() the same
// way `rasqlgen schema -source` reads a schema source package: directory
// must resolve to a package inside a Go module, and a temporary package
// main, written beside it and removed afterward, imports that package,
// calls Tables(), and JSON-encodes the result to stdout for this process
// to read back. Nothing else can hand this process directory's compiled
// Tables() result, since directory's package is not known at this
// program's own build time.
func loadExistingDescriptionTables(ctx context.Context, directory string) ([]schema.TableDef, error) {
	pkg, err := sourcepkg.Resolve(ctx, directory)
	if err != nil {
		return nil, err
	}

	program := descriptionLoaderProgram(pkg.ImportPath)
	stdout, err := pkg.Capture(ctx, ".rasqlgen-bootstrap-refresh-", program)
	if err != nil {
		return nil, fmt.Errorf("load existing description package %s: %w", pkg.ImportPath, err)
	}

	var tables []schema.TableDef
	if err := json.Unmarshal(stdout, &tables); err != nil {
		return nil, fmt.Errorf("decode existing description package %s: %w", pkg.ImportPath, err)
	}
	return tables, nil
}

// descriptionLoaderProgram builds the temporary package main
// loadExistingDescriptionTables writes, runs, and deletes. It is built the
// same way schemaSourceProgram is, with a bytes.Buffer and strconv.Quote
// for the one baked-in value, for the same reason: a format template would
// force every literal '%' in the imported package's own error messages to
// be escaped.
func descriptionLoaderProgram(importPath string) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by rasqlgen; DO NOT EDIT.\n\n")
	buf.WriteString("package main\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"encoding/json\"\n")
	buf.WriteString("\t\"fmt\"\n")
	buf.WriteString("\t\"os\"\n\n")
	buf.WriteString("\tschemasource " + strconv.Quote(importPath) + "\n")
	buf.WriteString(")\n\n")
	buf.WriteString("func main() {\n")
	buf.WriteString("\tdata, err := json.Marshal(schemasource.Tables())\n")
	buf.WriteString("\tif err != nil {\n")
	buf.WriteString("\t\tfmt.Fprintln(os.Stderr, err)\n")
	buf.WriteString("\t\tos.Exit(1)\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\tos.Stdout.Write(data)\n")
	buf.WriteString("}\n")
	return buf.Bytes()
}
